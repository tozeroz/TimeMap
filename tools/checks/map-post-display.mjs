// Run with the isolated fixture server from server/tests/map-display.test.ts (MAP_TEST_SERVE=1).
import { createRequire } from 'node:module'
import { homedir } from 'node:os'
import { join } from 'node:path'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'))
const browser = await chromium.launch({ headless: true, executablePath: join(homedir(), 'AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe') })
const page = await browser.newPage({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce', hasTouch: true, isMobile: true })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const tile = '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#f2f3f1"/><path d="M0 65H256M0 190H256M80 0V256M210 0V256" stroke="white" stroke-width="12"/><path d="M0 65H256M80 0V256" stroke="#dedfdd" fill="none"/></svg>'
try {
  // Only map tiles and media are deterministic fixtures. API counts and sorting use real PostgreSQL.
  await page.route('**/appmaptile?**', route => route.fulfill({ contentType: 'image/svg+xml', body: tile }))
  await page.route('**/api/media/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="300" height="300"><rect width="300" height="300" rx="25" fill="#cbdaca"/><circle cx="160" cy="140" r="80" fill="#e5b882"/><text x="35" y="265" font-size="28" fill="#344b47">校园日常</text></svg>' }))
  await page.goto((process.env.MAP_UI_URL ?? 'http://127.0.0.1:5189/') + '#/map?raster=1')
  await page.locator('.rm[data-visible="true"] .rm__count').first().waitFor()
  const dismiss = page.locator('.map__modal-btn')
  if (await dismiss.count()) await dismiss.first().click()
  await page.waitForTimeout(1100)
  const host = page.locator('.realmaps')
  assert.equal(await host.getAttribute('data-provider'), 'raster')
  const instance = await host.evaluate(el => { el.dataset.testInstance = 'same-map'; return el.dataset.testInstance })
  assert.equal(await page.locator('button.rm__count').count(), 0, 'post count is plain noninteractive text')
  const stackButton = page.locator('.rm[data-visible="true"][data-stack-visible="true"] .rm__stack').first()
  await stackButton.click()
  await page.locator('.map-posts__row').first().waitFor()
  assert.match(page.url(), /preview=/)
  assert.equal(await host.getAttribute('data-test-instance'), instance, 'opening preview must not recreate map')
  const box = await page.locator('.map-posts').boundingBox()
  const mapBox = await page.locator('.map').boundingBox()
  assert(Math.abs(box.height / mapBox.height - .5) < .05)
  await page.getByRole('button', { name: '加载更多帖子', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.map-posts__row').length > 20)
  await page.locator('.map-posts__body').evaluate(el => { el.scrollTop = 0 })
  const listBox = await page.locator('.map-posts__body').boundingBox()
  const cdp = await page.context().newCDPSession(page)
  const x = listBox.x + listBox.width * .6
  const y = listBox.y + listBox.height * .8
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  for (let i = 1; i <= 8; i++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - i * 18 }] })
    await page.waitForTimeout(20)
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.waitForTimeout(300)
  assert(await page.locator('.map-posts__body').evaluate(el => el.scrollTop > 30), 'native touch scrolling works inside preview')
  await page.locator('.map-posts__body').evaluate(el => { el.scrollTop = 250 })
  const firstPost = await page.locator('.map-posts__row').first().getAttribute('aria-label')
  await page.locator('.map-posts__row').nth(5).click()
  await page.waitForURL('**/feed?*')
  await page.goBack()
  await page.locator('.map-posts__row').first().waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.map-posts__row').length > 20)
  assert.equal(await page.locator('.map-posts__row').first().getAttribute('aria-label'), firstPost)
  await page.waitForTimeout(250)
  assert(await page.locator('.map-posts__body').evaluate(el => el.scrollTop >= 200), 'return restores list scroll')
  await mkdir('.local/map-ui-checks', { recursive: true })
  await page.screenshot({ path: '.local/map-ui-checks/phone-preview.png' })
  await page.getByRole('button', { name: '关闭帖子预览', exact: true }).click()
  await page.locator('.map-posts').waitFor({ state: 'detached' })
  await page.waitForTimeout(1000)
  await page.screenshot({ path: '.local/map-ui-checks/phone-map.png' })
  const before = await host.getAttribute('data-center')
  await page.locator('.rm[data-visible="true"][data-stack-visible="true"] .rm__stack').first().click()
  await page.locator('.map-posts__row').first().waitFor()
  await page.waitForTimeout(1000)
  // User panning while preview is open is retained on close.
  const rect = await host.boundingBox()
  await page.mouse.move(rect.x + 25, rect.y + 80)
  await page.mouse.down(); await page.mouse.move(rect.x + 90, rect.y + 125, { steps: 12 }); await page.mouse.up()
  await page.waitForTimeout(500)
  const moved = await host.getAttribute('data-center')
  assert.notEqual(moved, before)
  assert.equal(await page.locator('.map-posts').count(), 1)
  await page.keyboard.press('Escape')
  await page.locator('.map-posts').waitFor({ state: 'detached' })
  await page.waitForTimeout(800)
  assert.equal(await host.getAttribute('data-center'), moved, 'closing must preserve user pan')
  await page.setViewportSize({ width: 812, height: 375 })
  await page.waitForTimeout(400)
  await page.screenshot({ path: '.local/map-ui-checks/landscape-map.png' })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '24px' })
  await page.waitForTimeout(400)
  await page.locator('.rm[data-visible="true"][data-stack-visible="true"] .rm__stack').first().click()
  await page.locator('.map-posts__close').waitFor()
  const closeBox = await page.locator('.map-posts__close').boundingBox()
  assert(closeBox.x >= 0 && closeBox.x + closeBox.width <= 375 && closeBox.y + closeBox.height < 812)
  await page.keyboard.press('Escape')
  await page.locator('.map-posts').waitFor({ state: 'detached' })
  assert.deepEqual(errors, [])
  console.log('PASS: 375px raster map, independent post entry, half-screen preview, pagination, detail/back/scroll restoration, user pan retained, Escape close, landscape; no page errors')
} finally { await browser.close() }
