-- ═══════════════════════════════════════════════════════════════════════════
-- 这次发布的是什么（如实说明，不夸大）
-- ═══════════════════════════════════════════════════════════════════════════
--   · latest_version = '1.3.1'
--     —— 与 `app/src/version.ts` 的 APP_VERSION **一致**、
--        也与 `app/android/app/build.gradle` 的 versionName **一致**（门禁机械校验）。
--   · apk_url = http://8.148.156.146/download/campus-demo-1.3.1.apk
--     —— 安装包由 `tools/release-apk.ps1` 上传（本机 PS7 下该脚本不可用，见部署记录
--        的手工等价步骤），上传后必须校验 sha256 与 HTTP 200。
--     ⚠️ 用 **http**（不是 https）是**有意**的：线上是私有 CA 自签证书，
--        下载器会对 APK 下载给出证书告警；80 端口在同一份配置里可用。
--   · notes 只写**实际包含的改动**，不写编造的功能亮点。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 1.3.1 的内容：只修一类缺陷 + 一个配套入口
-- ═══════════════════════════════════════════════════════════════════════════
--   · 修复：旧版本发帖只在手机本地留下 `mine-…` 记录（从未上传），点开时前端拿它
--     去请求 `/api/posts/<id>`，服务端回 400 invalid_id ⇒ 界面显示「网络错误」。
--     现在详情页先查本地库并如实说明"只在这台设备上"，给出重新发布/删除出口。
--   · 新增：「我的」→「清除本机缓存」，只清本机遗留帖与接口快照，保留登录态。
--
-- ⚠️ 顺序要求（发布纪律）：**先**把 campus-demo-1.3.1.apk 传到服务器并校验通过，
--    再让服务端执行本迁移（服务启动时会自动应用）。反过来就是"清单说 1.3.1、点下载 404"。
--
-- ⚠️ 本迁移**幂等**：只在当前生效行的版本还不是 1.3.1 时更新；重复执行无副作用。
-- ---------------------------------------------------------------------------
update app_release
   set latest_version = '1.3.1',
       apk_url        = 'http://8.148.156.146/download/campus-demo-1.3.1.apk',
       notes          = '演示版本 1.3.1（本仓库自行构建并托管）。相对 1.3：修复旧版本只在手机本地留下的动态（mine-* 记录）点开必报「网络错误」的问题 —— 现在会如实说明该内容只存在于本机，并提供「重新发布」「删除」两条出口；信息流对这些记录显示「仅本机」角标；「我的」新增「清除本机缓存」，只清本机遗留动态与页面缓存，不影响登录状态。',
       updated_at     = now()
 where active = true
   and latest_version <> '1.3.1';
