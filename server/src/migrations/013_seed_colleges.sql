create table if not exists colleges (
  id uuid primary key,
  school_id uuid not null references schools (id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  -- 同一学校下学院名唯一（避免重复种）
  unique (school_id, name)
);

create index if not exists colleges_school_idx on colleges (school_id, sort_order);

comment on table colleges is
  '学院（baseline/observation-derived fixture，非生产同步）。种子来源：Round 319 对原版认证页「所在学院」picker 的只读 dump（5 条，可能非完整列表 ⇒ ORIGINAL_COLLEGE_LIST_COMPLETE: NOT_EVALUATED）。';

