-- 发布 App 1.3（自更新清单指向**我们自己构建并托管**的安装包）
--
-- 与 015 / 018 同一套纪律：版本号这类"需要长期成立的状态"用**迁移**落库，
-- 而不是直接 UPDATE 数据库 —— 后者会让线上状态无法从仓库重建。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 这次发布的是什么（如实说明，不夸大）
-- ═══════════════════════════════════════════════════════════════════════════
--   · latest_version = '1.3'
--     —— 与 `app/src/version.ts` 的 APP_VERSION **一致**、
--        也与 `app/android/app/build.gradle` 的 versionName **一致**（门禁机械校验）。
--   · apk_url = http://8.148.156.146/download/campus-demo-1.3.apk
--     —— 安装包由 `tools/release-apk.ps1` 上传，上传后必须校验 sha256 与 HTTP 200。
--     ⚠️ 用 **http**（不是 https）是**有意**的：线上是私有 CA 自签证书，
--        下载器会对 APK 下载给出证书告警；80 端口在同一份配置里可用。
--   · notes 只写**实际包含的改动**，不写编造的功能亮点。
--
-- ⚠️ 顺序要求（发布纪律）：**先**把 campus-demo-1.3.apk 传到服务器并校验通过，
--    再让服务端执行本迁移（服务启动时会自动应用）。反过来就是"清单说 1.3、点下载 404"。
--
-- ⚠️ 本迁移**幂等**：只在当前生效行的版本还不是 1.3 时更新；重复执行无副作用。
-- ---------------------------------------------------------------------------
update app_release
   set latest_version = '1.3',
       apk_url        = 'http://8.148.156.146/download/campus-demo-1.3.apk',
       notes          = '演示版本 1.3（本仓库自行构建并托管）。相对 1.2：帖子列表支持最新/热门排序与按地标筛选（含多选）、活动列表支持服务端状态与地标筛选、地点详情默认按热门展示并改为双列卡片、新增「我的发布」双列页、账号设置页改为真实数据、错误提示改为可读文案、修复分享/图片预览/地图标记点击等缺陷。',
       updated_at     = now()
 where active = true
   and latest_version <> '1.3';
