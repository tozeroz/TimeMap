-- 017_admin_password：为**管理员**恢复密码凭据（学生仍走手机验证码）
--
-- ⚠️⚠️ 这是一次**有意的反转**，必须把理由和边界写清楚，否则下一个人会以为
--     password_hash 是 005 没删干净的遗留物、又把它删掉。
--
-- ## 为什么要反转（2026-09-26 的真实运维困境）
--   005 把密码整列删掉的理由是"原版登录页实测没有密码"——那对**学生**依然成立。
--   但管理员有一条学生没有的需求：**在短信通道不可用时仍要能进管理端**。
--   实测踩到：线上阿里云短信发送失败（`503 sms_delivery_failed`）⇒ request-code 直接失败
--   ⇒ **谁也登不进去**，包括管理员 ⇒ 管理端完全不可达，而管理端恰恰是"出事了要进去处理"的地方。
--   ⇒ 把凭据**唯一化**到一条依赖第三方通道的路径上，等于给整个管理能力绑了一个单点故障。
--
-- ## 边界（刻意收紧，不是"把密码登录加回来"）
--   1. **只有 role='admin' 能用密码登录**。学生账号的 password_hash 恒为 NULL，
--      密码登录接口对学生一律返回与"密码错误"完全相同的响应（不泄露账号是否存在/是否管理员）。
--   2. 列的注释里写明这条边界（见下面 COMMENT），让"能不能给普通用户设密码"这件事有据可依。
--   3. 哈希用 scrypt（Node 内置 crypto，零新依赖），参数与格式见 server/src/password.ts。
--   4. 保留"短信验证码"作为管理员的**另一条**可用路径 —— 恢复的是**多一条**路，不是换一条路。
--
-- ## 向后兼容
--   纯加列、可空、带 `IF NOT EXISTS` ⇒ 对既有数据与学生流程零影响；重复执行安全。

-- ---------------------------------------------------------------------------
-- 凭据列（可空：学生恒为 NULL）
-- ---------------------------------------------------------------------------
ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash text;

-- 格式约束：要么为空（学生），要么是我们自己的 scrypt 编码串。
-- ⚠️ 用前缀钉住算法版本，将来换参数/算法时能识别旧格式，而不是"看起来都是 hex 串"。
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_password_hash_format;
ALTER TABLE users ADD CONSTRAINT users_password_hash_format
  CHECK (password_hash IS NULL OR password_hash ~ '^scrypt\$\d+\$\d+\$\d+\$[0-9a-f]+\$[0-9a-f]+$');

COMMENT ON COLUMN users.password_hash IS
  '管理员密码凭据（scrypt）。**仅 role=admin 可用**：学生登录只有「手机号+验证码」一条路径，'
  '其 password_hash 恒为 NULL。加它的原因见 017 迁移头部（短信通道故障时管理端必须仍可达）。'
  '格式：scrypt$N$r$p$salt_hex$hash_hex';

-- ---------------------------------------------------------------------------
-- 审计：谁在什么时候设过密码（管理员凭据变更要留痕）
-- ---------------------------------------------------------------------------
-- 复用既有 audit_log（016 建的表）即可，这里只补一条说明，不新建表：
--   action='admin_password_set' / targetType='user' / targetId=<被设密码的 user id>
--   ⚠️ **绝不记录密码或哈希本身**，只记"谁给谁设了密码"。
COMMENT ON TABLE audit_log IS
  '操作记录（F07/US-08：管理员、对象、时间、动作）。'
  '017 起也记录管理员密码变更（action=admin_password_set），但**不记录密码或哈希**。';
