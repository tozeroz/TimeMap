--    公开地点列表、地图、发帖选择器都只取 enabled 地点，因此它们会消失。
-- 3. 南门：031 把坐标写成表格值 39.9492, 116.3415；生产原值是 39.949253, 116.341471。
--    仅当当前值仍是 031 写入的值时才恢复，人工改过的坐标不覆盖。
--
-- 幂等：每条 UPDATE 都带「当前值不同」条件，重跑不产生变化。

