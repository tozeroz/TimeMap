-- ---------------------------------------------------------------------------
-- P0 收尾：发布 App 1.2（自更新清单指向**我们自己构建并托管**的安装包）
--
-- ⚠️ 为什么用**迁移**而不是直接 UPDATE 数据库：
--   直接改库会让"仓库"与"线上实际状态"脱节（drift）。凡是**需要长期成立的状态**，
--   都要能从仓库重建。（同 015 的理由，见 015 顶部记录。）
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 这次发布的是什么（如实说明，不夸大）
-- ═══════════════════════════════════════════════════════════════════════════
--   · latest_version = '1.2'
--     —— 与 `app/src/version.ts` 的 APP_VERSION **一致**、
--        也与 `app/android/app/build.gradle` 的 versionName **一致**（由门禁机械校验）。
--   · apk_url = http://8.148.156.146/download/campus-demo-1.2.apk
--     —— Nginx `location /download/` → `alias /srv/campus/downloads/`（见
--        ops/nginx/campus-locations.inc）。安装包由 `tools/release-apk.ps1` 上传，
--        上传后**必须**校验 sha256 + HTTP 200 + Content-Type 才允许执行本迁移。
--     ⚠️ 用 **http**（不是 https）是**有意**的：线上是**私有 CA 自签证书**，
--        下载器会对 APK 下载给出证书告警；80 端口在同一份配置里可用。
--        这是**已知取舍**，不是疏忽。
--   · notes 写清这是什么，**不写**编造的"功能亮点"。
--
-- ⚠️ 顺序要求（发布纪律）：**先**把 campus-demo-1.2.apk 传上服务器并校验通过，
--    **再**执行本迁移。反过来会出现"清单说 1.2、点下载 404"的假发布。
--
-- ⚠️ 本迁移**幂等**：只在当前"生效行"的版本还不是 1.2 时更新；重复执行无副作用。
-- ---------------------------------------------------------------------------
update app_release
   set latest_version = '1.2',
       apk_url        = 'http://8.148.156.146/download/campus-demo-1.2.apk',
       notes          = '演示版本 1.2（本仓库自行构建并托管）。此版本补齐 P0 功能：账号资料、地图地点与详情、发帖、互动（点赞/收藏/评论/转发）、活动、举报与管理端，并新增管理员密码登录。',
       updated_at     = now()
 where active = true
   and latest_version <> '1.2';
