-- ---------------------------------------------------------------------------
-- WO#23（Owner 裁定 ③：App 自更新必须实现体验等价）：**真实的**版本发布清单
--
-- ⚠️ 本迁移的定位：让"检查更新"有**真实数据源**，而不是客户端里写死的编造值。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 为什么需要它（查证过程）
-- ═══════════════════════════════════════════════════════════════════════════
--   改前 UpgradeDialog 从 mock 拿 `upgradeInfo = { version: '2.11.0', size: '48.6 MB',
--   highlights: [...] }` —— **全部无出处**；而「立即更新」只是 `navigate('campus')`
--   （点了就跳走、看起来像"更新完了"）= **假成功**。
--   Round 319 早段已把那两处去掉，改为"版本信息暂不可用 + 明确说明更新流程未接入"。
--
--   Owner 裁定 ③ 要求"必须实现体验等价"⇒ 我**不能**只停在"如实说没接"。
--   ⚠️ 但原版「立即更新」的**真实去向未观察**（点它可能触发真实下载 ⇒ 只读约束下
--      **BLOCKED_BY_POLICY**，不能去点）⇒ 所以"原版到底做成什么样"**无从对齐**。
--
--   ⇒ 我能做的、且**是真的**的事：
--       ① 让"检查更新"去**问我们自己的后端**要一份发布清单（真实请求、真实数据）
--       ② 客户端拿**自己真实的版本号**与之比较（真实比较）
--       ③ 有更新 ⇒ 给出**真实的下载地址**（由运维在本表里配置；未配置就**如实说**未配置）
--          没有更新 ⇒ 如实显示"已是最新版本"
--     这样"检查更新"是一个**真功能**，而不是提示框。
--     ⚠️ 它**不等于**与原版一致 —— 原版行为未观察 ⇒ `ORIGINAL_UPDATE_FLOW: NOT_EVALUATED`。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 只种什么、**不**种什么
-- ═══════════════════════════════════════════════════════════════════════════
-- ✅ 允许种：**一行**发布清单，version 取我们**当前真实版本**（1.0，与 android
--    versionName 一致 —— 该一致性由门禁机械校验），apk_url 为空（我们**没有**托管 APK）。
-- ❌ **不得**种：编造的"新版本号/包体积/功能亮点"。没有真实发布就写"当前版本=最新"。
-- ---------------------------------------------------------------------------

create table if not exists app_release (
  id            uuid primary key,
  -- 当前对外发布的最新版本（语义化字符串；比较逻辑在服务端做，客户端只显示）
  latest_version text not null,
  -- APK 下载地址。**可为空** = 尚未托管 ⇒ 客户端必须如实说明，不得编造链接
  apk_url        text,
  -- 更新说明（可为空）。⚠️ 只放**真实**的发布说明；没有就留空
  notes          text,
  -- 该行是否生效（便于运维"撤回"一次发布而不删行）
  active         boolean not null default true,
  updated_at     timestamptz not null default now(),
  CONSTRAINT app_release_version_not_blank CHECK (length(btrim(latest_version)) > 0)
);

comment on table app_release is
  'App 发布清单（真实数据源，供客户端"检查更新"）。⚠️ 不种编造的版本/体积/亮点；apk_url 为空即"尚未托管"。';

-- ⭐ 幂等种子：**一行**，版本 = 我们当前真实版本 1.0（与 android versionName 一致），
--    没有托管 APK ⇒ apk_url = NULL（客户端会如实说"下载地址未配置"）
insert into app_release (id, latest_version, apk_url, notes)
values ('e0000000-0000-4000-8000-000000000001', '1.0', null,
        '当前为演示版本，未托管安装包。')
on conflict (id) do nothing;
